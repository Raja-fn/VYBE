/**
 * Bundles the server into supabase/functions/api/server.js for the Supabase
 * Edge runtime (Deno). Our code, zod and the config defaults are bundled;
 * the Postgres driver is loaded from npm by Deno; node: built-ins stay as-is.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const POSTGRES = 'npm:postgres@3.4.7';

await build({
  entryPoints: [join(root, 'src/api/edge.ts')],
  outfile: join(root, '../supabase/functions/api/server.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['import', 'default'],
  legalComments: 'none',
  banner: { js: '// Generated by `npm --prefix server run build:edge`. Do not edit; change server/src instead.' },
  plugins: [
    {
      name: 'deno-externals',
      setup(b) {
        b.onResolve({ filter: /^postgres$/ }, () => ({ path: POSTGRES, external: true }));
        b.onResolve({ filter: /^node:/ }, (args) => ({ path: args.path, external: true }));
      },
    },
  ],
});
console.log('Built supabase/functions/api/server.js');
